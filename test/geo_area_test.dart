/// Мекенжай таңдаудың ГЕОГРАФИЯ ережелері.
///
/// Не тексереміз: клиент қала таңдап, картадан сол қаланың МАҢЫНДАҒЫ ауыл
/// не кентті белгілегенде — нүкте қабылдана ма. Бұрын қабылданбайтын:
/// салыстыру тек қала АТЫ бойынша жүретін де, «Астана» таңдалып тұрғанда
/// Ерейментаудағы, «Тараз» таңдалып тұрғанда Меркі/Луговойдағы нүкте
/// «бұл қала емес» деп қайтарылатын. Ал клиенттердің үлкен бөлігі дәл сол
/// қала маңындағы елді мекендерде тұрады.
///
/// Координаталар — OSM/Nominatim-нен алынған НАҚТЫ деректер (болжам емес),
/// Қазақстанның барлық облысын қамтиды.
void main() {
  group('Geo.displayCity — әкімшілік жұрнақтарды тазалау', () {
    // Nominatim қала атауын кеңсе түрінде қайтарады. Адрес жолында
    // «Ерейментау қаласы әкімдігі» деп тұрмауы керек.
    const cases = {
      'Ерейментау қаласы әкімдігі': 'Ерейментау',
      'Қаскелең қалалық әкімдігі': 'Қаскелең',
      'Шемонаиха қаласының әкімшілігі': 'Шемонаиха',
      'Риддер қалалық әкімдігі': 'Риддер',
      'Мерке ауылдық округі': 'Мерке',
      'Текелі Қ.Ә.': 'Текелі',
      'Тараз қаласы': 'Тараз',
      'Ерейментау ауданы': 'Ерейментау',
      // Тазалауға жатпайтындар өзгеріссіз қалуы керек.
      'Меркі': 'Меркі',
      'Луговой': 'Луговой',
      'Астана': 'Астана',
    };

    cases.forEach((raw, expected) {
      test('$raw → $expected', () {
        expect(Geo.displayCity(raw), expected);
      });
    });

    test('жұрнақ жеке сөз болмаса қиылмайды (атау бүлінбеуі керек)', () {
      // «Белгород» соңы «город», бірақ бұл жұрнақ емес — атаудың бөлігі.
      expect(Geo.displayCity('Белгород'), 'Белгород');
      expect(Geo.displayCity('Ақсело'), 'Ақсело');
    });
  });

  group('Geo.sameCity — кеңсе атауы мен қарапайым атау бір қала', () {
    test('әкімшілік түрі мен қысқа түрі теңеледі', () {
      expect(Geo.sameCity('Ерейментау қаласы әкімдігі', 'Ерейментау'), isTrue);
      expect(Geo.sameCity('Тараз қалалық әкімшілігі', 'Тараз'), isTrue);
      expect(Geo.sameCity('Қаскелең қалалық әкімдігі', 'Қаскелең'), isTrue);
    });

    test('бөлек қалалар теңелмейді', () {
      expect(Geo.sameCity('Астана', 'Алматы'), isFalse);
      expect(Geo.sameCity('Тараз', 'Шымкент'), isFalse);
    });
  });

  group('Geo.anchorCity — әр тірек қала өзін табады', () {
    // Тізімдегі әр қаланың дәл ортасы сол қаланы қайтаруы керек.
    for (final e in kzCityCenters.entries) {
      test(e.key, () => expect(Geo.anchorCity(e.value), e.key));
    }

    test('Қазақстаннан тыс алыс нүкте — тірек қала жоқ', () {
      // Мәскеу маңы: 250 км шегінен әлдеқайда алыс.
      expect(Geo.anchorCity(const LatLng(55.75, 37.61)), isNull);
    });
  });

  group('Geo.inCityArea — қала маңындағы елді мекендер (бүкіл ҚР)', () {
    for (final s in _settlements) {
      test('${s.name} ← ${s.city}', () {
        final p = LatLng(s.lat, s.lng);
        expect(Geo.anchorCity(p), s.anchor,
            reason: '${s.name}: тірек қала');
        expect(Geo.inCityArea(p, s.city), s.accepted,
            reason: '${s.name}: ${s.city} аймағында ма');
      });
    }

    test('клиент шағымындағы нақты жағдайлар үнсіз өтеді', () {
      // Астана таңдалып, Ерейментау белгіленді — бұрын МҮЛДЕМ таңдалмайтын.
      expect(Geo.inCityArea(const LatLng(51.6199, 73.1033), 'Астана'), isTrue);
      // Тараз таңдалып, Меркі/Луговой белгіленді.
      expect(Geo.inCityArea(const LatLng(42.8651, 73.1861), 'Тараз'), isTrue);
      expect(Geo.inCityArea(const LatLng(42.9423, 72.7544), 'Тараз'), isTrue);
    });

    test('екі шарттың ЕКЕУІ де қажет', () {
      // 1) Тек қашықтық жеткіліксіз: Меркі Тараздан ~148 км — радиустың дәл
      //    шетінде, бірақ ең жақын тірек қала Тараз болғандықтан өтеді.
      final merki = Geo.haversineKm(
          const LatLng(42.8651, 73.1861), kzCityCenters['Тараз']!);
      expect(merki, greaterThan(140));
      expect(Geo.anchorCity(const LatLng(42.8651, 73.1861)), 'Тараз');

      // 2) Тек тірек қала жеткіліксіз: Ерейментауға Степногорск жақынырақ,
      //    бірақ Астанадан 150 км шегінде болғандықтан өтеді.
      expect(Geo.anchorCity(const LatLng(51.6199, 73.1033)), 'Степногорск');
      expect(
          Geo.haversineKm(
              const LatLng(51.6199, 73.1033), kzCityCenters['Астана']!),
          lessThan(Geo.cityAreaRadiusKm));
    });

    test('мүлдем басқа облыс аймаққа кірмейді', () {
      // Алматыдағы нүкте «Тараз» таңдалып тұрғанда өтпеуі керек — әйтпесе
      // тапсырыс мүлдем басқа қаланың орындаушыларына кетеді.
      expect(Geo.inCityArea(kzCityCenters['Алматы']!, 'Тараз'), isFalse);
      expect(Geo.inCityArea(kzCityCenters['Астана']!, 'Шымкент'), isFalse);
      expect(Geo.inCityArea(kzCityCenters['Ақтау']!, 'Өскемен'), isFalse);
    });

    test('Қазақстаннан тыс нүкте ешқашан қабылданбайды', () {
      expect(Geo.inCityArea(const LatLng(55.75, 37.61), 'Астана'), isFalse);
    });
  });

  group('GeoAddress.labelFor — нысан аты мен елді мекен адреске түседі', () {
    test('ТРЦ/дүкен аты көше алдында тұрады', () {
      // Клиенттің шағымы: үлкен ғимаратты белгілегенде «жәй ғана көше»
      // жазылатын. Енді нысан аты бірінші тұруы керек.
      const a = GeoAddress(
        poi: 'Хан Шатыр',
        street: 'Тұран даңғылы, 37',
        settlement: 'Астана',
        point: LatLng(51.1325, 71.4025),
      );
      expect(a.labelFor('Астана'), 'Хан Шатыр, Тұран даңғылы, 37');
    });

    test('таңдалған қала адресте ҚАЙТАЛАНБАЙДЫ', () {
      const a = GeoAddress(
        poi: null,
        street: 'Бараева, 25',
        settlement: 'Астана',
        point: LatLng(51.16, 71.47),
      );
      expect(a.labelFor('Астана'), 'Бараева, 25');
      // Кеңсе түрінде келсе де қайталанбауы керек.
      const b = GeoAddress(
        poi: null,
        street: 'Бараева, 25',
        settlement: 'Астана қаласы әкімдігі',
        point: LatLng(51.16, 71.47),
      );
      expect(b.labelFor('Астана'), 'Бараева, 25');
    });

    test('бөтен елді мекен адреске МІНДЕТТІ түрде қосылады', () {
      // Орындаушы қайда баратынын адрестің өзінен көруі керек.
      const a = GeoAddress(
        poi: null,
        street: 'Абай көшесі, 140',
        settlement: 'Ерейментау',
        point: LatLng(51.6199, 73.1033),
      );
      expect(a.labelFor('Астана'), 'Ерейментау, Абай көшесі, 140');

      const b = GeoAddress(
        poi: 'Магнум',
        street: 'Асанбая Асқарова, 62',
        settlement: 'Меркі',
        point: LatLng(42.8651, 73.1861),
      );
      expect(b.labelFor('Тараз'), 'Меркі, Магнум, Асанбая Асқарова, 62');
    });

    test('ештеңе табылмаса координата қайтады (бос жол емес)', () {
      const a = GeoAddress(
        poi: null,
        street: null,
        settlement: null,
        point: LatLng(51.16, 71.47),
      );
      expect(a.labelFor('Астана'), contains('51.16'));
    });
  });
}

