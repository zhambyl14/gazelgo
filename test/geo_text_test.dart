    test('қазақ/орыс әріптері, ё/й/ы, ь, қос әріп', () {
      expect(GeoText.fold('Төле би'), GeoText.fold('Толе би'));
      expect(GeoText.fold('Желтоқсан'), GeoText.fold('Жельтоксан'));
      expect(GeoText.fold('Мәңгілік Ел'), GeoText.fold('Мангилик ел'));
      expect(GeoText.fold('Новосёлов'), GeoText.fold('Новоселов'));
      expect(GeoText.fold('Сейфуллин'), GeoText.fold('Сейфулин'));
    });

    test('латын → кирилл', () {
      expect(GeoText.fold('abaya'), GeoText.fold('Абая'));
      expect(GeoText.fold('Satpayev'), GeoText.fold('Сатпаев'));
      expect(GeoText.fold('Shakarim'), GeoText.fold('Шәкәрім'));
      expect(GeoText.fold('Raiymbek'), GeoText.fold('Райымбек'));
      expect(GeoText.isMostlyLatin('abaya 15'), isTrue);
      expect(GeoText.isMostlyLatin('Абая 15'), isFalse);
    });

    test('тип сөздер мен шағын аудандар өзекке кірмейді', () {
      expect(GeoText.streetCore('Төле би көшесі'), 'толеби');
      expect(GeoText.streetCore('улица Толе би'), 'толеби');
      expect(GeoText.streetCore('6-й микрорайон'), 'мкр6');
      expect(GeoText.streetCore('мкр. 6'), 'мкр6');
      expect(GeoText.streetCore('6 шағын ауданы'), 'мкр6');
      expect(GeoText.streetCore('2-я Южная улица'), '2южная');
    });
  });

