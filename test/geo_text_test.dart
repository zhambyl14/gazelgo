import 'package:tasu/core/geo_text.dart';

/// Қатеге төзімді мекенжай іздеудің ЕРЕЖЕЛЕРІ — бүкіл Қазақстан бойынша.
///
/// Атаулар — OpenStreetMap-тегі НАҚТЫ көше атаулары (әр облыс орталығынан,
/// Overpass арқылы алынған, 2026-10). Клиент оларды қалай жазатыны — қате
/// әріп, латын, орысша жалғау, бос орынсыз, тип сөзсіз.
