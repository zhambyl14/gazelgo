  /// [names] ішінен [query]-ге ең ұқсас атаулар (ұқсастығы бойынша).
  List<String> top(
    List<String> names,
    String query, {
    String? city,
    int k = 3,
  }) {
    final q = AddressQuery.parse(query, city: city);
    final qk = NameKey.query(q.street);
    final scored = [
      for (final n in names) (n, GeoText.similarityKey(qk, NameKey(n))),
    ].where((e) => e.$2 >= 0.6).toList()..sort((a, b) => b.$2.compareTo(a.$2));
    return scored.take(k).map((e) => e.$1).toList();
  }

