      expect(a.street, 'абая');
      expect(a.house, '15');
      expect(AddressQuery.parse('Абая 15 а').house, '15а');
      expect(AddressQuery.parse('Абая 15/2').house, '15/2');
      expect(AddressQuery.parse('6 мкр 12').house, '12');
      expect(AddressQuery.parse('6 мкр 12').core, 'мкр6');
    });

    test('жалғыз нөмір — атаудың бөлігі (19 мкр)', () {
      final a = AddressQuery.parse('19 мкр');
      expect(a.house, isNull);
      expect(a.core, 'мкр19');
    });

    test('қала атымен аталған көше жоғалмайды', () {
      final a = AddressQuery.parse('Тараз даңғылы 5', city: 'Тараз');
      expect(a.core, 'тараз');
      expect(a.house, '5');
    });

    test('латынмен жазылса — геокодерге кириллмен', () {
      final a = AddressQuery.parse('abaya 15');
      expect(a.text, 'абая 15');
      expect(a.house, '15');
    });
  });

