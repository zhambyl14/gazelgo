/// Заңдық құжаттар: Пайдаланушы келісімі (оферта) + Құпиялылық саясаты.
///
/// ҚР «Дербес деректер және оларды қорғау туралы» Заңы (94-V) бойынша
/// деректерді жинауға келісім МІНДЕТТІ, ал App Store / Play Market екеуі де
/// қосымша ішінен ашылатын құпиялылық саясатын талап етеді. Мәтіндер осында
/// статикалық сақталады — интернетсіз де ашылады.
class LegalScreen extends StatelessWidget {
  /// 0 — Пайдаланушы келісімі, 1 — Құпиялылық саясаты.
  final int initialTab;
  const LegalScreen({super.key, this.initialTab = 0});

  @override
  Widget build(BuildContext context) {
    return DefaultTabController(
      length: 2,
      initialIndex: initialTab,
      child: Scaffold(
        appBar: AppBar(
          title: const Text('Заңдық құжаттар'),
          bottom: const TabBar(tabs: [
            Tab(text: 'Пайдаланушы келісімі'),
            Tab(text: 'Құпиялылық саясаты'),
          ]),
        ),
        body: const TabBarView(
          children: [
            _LegalText(kTermsText),
            _LegalText(kPrivacyText),
          ],
        ),
      ),
    );
  }
}

class _LegalText extends StatelessWidget {
  final String text;
  const _LegalText(this.text);

  @override
  Widget build(BuildContext context) {
    return SingleChildScrollView(
      padding: const EdgeInsets.all(20),
      child: Center(
        child: ConstrainedBox(
          constraints: const BoxConstraints(maxWidth: 640),
          child: SelectableText(
            text,
            style: const TextStyle(fontSize: 14, height: 1.55, color: Gz.ink),
          ),
        ),
      ),
    );
  }
}

