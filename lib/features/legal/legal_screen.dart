// Бұрын бүкіл құжат жалғыз `SelectableText` болып, бір-біріне жабысқан
// «қабырға мәтін» түрінде көрінетін: «1.», «1.1.», «2.» тақырыпшалары
// қарапайым сөйлемнен ажырамайтын. Енді мәтін ЖОЛМА-ЖОЛ талданып, әр
// түрі өз стилінде салынады (тақырып / бөлім / тармақ / тізім), сол
// себепті мәтін константалары ЖАЛҒЫЗ дереккөз болып қала береді —
// дизайн үшін мәтінді қайталаудың қажеті жоқ.

enum _BlockKind { title, subtitle, section, clause, bullet, plain }

class _Block {
  final _BlockKind kind;

  /// Көрсетілетін мәтін — нөмірі алынып тасталған түрі.
  final String text;

  /// «1.1» тәрізді тармақ нөмірі ([_BlockKind.clause] үшін).
  final String? number;

  /// Бөлім нөмірі ([_BlockKind.section] үшін) — скролл мақсаты.
  final int? sectionNo;

  const _Block(this.kind, this.text, {this.number, this.sectionNo});
}

/// «1. ЖАЛПЫ ЕРЕЖЕЛЕР» — бөлім тақырыбы (нөмірден кейін бос орын бар).
final _reSection = RegExp(r'^(\d+)\.\s+(.+)$');

/// «1.1. Tasu — …» — тармақ (нөмірде нүкте екеу).
final _reClause = RegExp(r'^(\d+\.\d+)\.\s+(.+)$');

List<_Block> _parseLegal(String raw) {
  final blocks = <_Block>[];
  var titleTaken = false;

  for (final rawLine in raw.trim().split('\n')) {
    final line = rawLine.trim();
    if (line.isEmpty) continue;

    if (!titleTaken) {
      titleTaken = true;
      blocks.add(_Block(_BlockKind.title, line));
      continue;
    }
    if (line.startsWith('Соңғы жаңартылуы') ||
        line.startsWith('Последнее обновление')) {
      blocks.add(_Block(_BlockKind.subtitle, line));
      continue;
    }
    if (line.startsWith('•')) {
      blocks.add(_Block(_BlockKind.bullet, line.substring(1).trim()));
      continue;
    }
    final clause = _reClause.firstMatch(line);
    if (clause != null) {
      blocks.add(_Block(_BlockKind.clause, clause.group(2)!,
          number: clause.group(1)));
      continue;
    }
    final section = _reSection.firstMatch(line);
    if (section != null) {
      blocks.add(_Block(_BlockKind.section, section.group(2)!,
          sectionNo: int.tryParse(section.group(1)!)));
      continue;
    }
    blocks.add(_Block(_BlockKind.plain, line));
  }
  return blocks;
}

class _LegalDoc extends StatefulWidget {
  final String text;
  final int? scrollToSection;
  const _LegalDoc(this.text, {this.scrollToSection});

  @override
  State<_LegalDoc> createState() => _LegalDocState();
}

class _LegalDocState extends State<_LegalDoc> {
  late final List<_Block> _blocks = _parseLegal(widget.text);
  final _sectionKeys = <int, GlobalKey>{};

  /// Қазір сары түспен белгіленіп тұрған бөлім (скроллдан кейін бірнеше
  /// секунд) — қолданушы қай жерге түскенін бірден көреді.
  int? _highlight;

  @override
  void initState() {
    super.initState();
    for (final b in _blocks) {
      if (b.sectionNo != null) _sectionKeys[b.sectionNo!] = GlobalKey();
    }
    final target = widget.scrollToSection;
    if (target != null && _sectionKeys.containsKey(target)) {
      _highlight = target;
      WidgetsBinding.instance.addPostFrameCallback((_) => _jumpTo(target));
    }
  }

  Future<void> _jumpTo(int section) async {
    final ctx = _sectionKeys[section]?.currentContext;
    if (ctx == null) return;
    await Scrollable.ensureVisible(
      ctx,
      duration: const Duration(milliseconds: 450),
      curve: Curves.easeOutCubic,
      // Бөлім тақырыбы экранның дәл жоғарғы жағында тұрсын.
      alignment: 0.04,
    );
    await Future<void>.delayed(const Duration(milliseconds: 1800));
    if (mounted) setState(() => _highlight = null);
  }

  @override
  Widget build(BuildContext context) {
    return SelectionArea(
      child: SingleChildScrollView(
        padding: const EdgeInsets.fromLTRB(20, 16, 20, 40),
        child: Center(
          child: ConstrainedBox(
            constraints: const BoxConstraints(maxWidth: 640),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [for (final b in _blocks) _block(b)],
            ),
          ),
        ),
      ),
    );
  }

  Widget _block(_Block b) => switch (b.kind) {
        _BlockKind.title => Padding(
            padding: const EdgeInsets.only(bottom: 4),
            child: Text(
              b.text,
              style: const TextStyle(
                fontSize: 20,
                fontWeight: FontWeight.w900,
                letterSpacing: -0.4,
                height: 1.25,
                color: Gz.ink,
              ),
            ),
          ),
        _BlockKind.subtitle => Padding(
            padding: const EdgeInsets.only(bottom: 8),
            child: Text(
              b.text,
              style: const TextStyle(fontSize: 12.5, color: Gz.textSecondary),
            ),
          ),
        _BlockKind.section => _sectionHeader(b),
        _BlockKind.clause => Padding(
            padding: const EdgeInsets.only(bottom: 10),
            child: Text.rich(
              TextSpan(
                style: const TextStyle(
                    fontSize: 14, height: 1.55, color: Gz.ink),
                children: [
                  // Тармақ нөмірі ӘРҚАШАН қалың әрі мәтіннен бөлек түсті:
                  // қолданушы «3.2» деп сілтеме жасағанда оны көзбен
                  // бірден табады.
                  TextSpan(
                    text: '${b.number}  ',
                    style: const TextStyle(
                      fontWeight: FontWeight.w900,
                      color: Gz.ink,
                    ),
                  ),
                  TextSpan(text: b.text),
                ],
              ),
            ),
          ),
        _BlockKind.bullet => Padding(
            padding: const EdgeInsets.only(left: 4, bottom: 8),
            child: Row(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Container(
                  margin: const EdgeInsets.only(top: 7, right: 10),
                  width: 6,
                  height: 6,
                  decoration: const BoxDecoration(
                    color: Gz.yellow,
                    shape: BoxShape.circle,
                  ),
                ),
                Expanded(
                  child: Text(
                    b.text,
                    style: const TextStyle(
                        fontSize: 14, height: 1.5, color: Gz.ink),
                  ),
                ),
              ],
            ),
          ),
        _BlockKind.plain => Padding(
            padding: const EdgeInsets.only(bottom: 10),
            child: Text(
              b.text,
              style:
                  const TextStyle(fontSize: 14, height: 1.55, color: Gz.ink),
            ),
          ),
      };

  /// Бөлім тақырыбы: нөмірі сары шеңберде, астында сары сызық — құжатты
  /// айналдырғанда бөлімдер бір-бірінен АНЫҚ ажырап тұрады.
  Widget _sectionHeader(_Block b) {
    final on = _highlight != null && _highlight == b.sectionNo;
    return AnimatedContainer(
      key: b.sectionNo == null ? null : _sectionKeys[b.sectionNo!],
      duration: const Duration(milliseconds: 500),
      margin: const EdgeInsets.only(top: 22, bottom: 12),
      padding: const EdgeInsets.fromLTRB(8, 8, 8, 10),
      decoration: BoxDecoration(
        color: on ? Gz.yellow.withValues(alpha: 0.28) : Colors.transparent,
        borderRadius: BorderRadius.circular(10),
        border: Border(
          bottom: BorderSide(color: Gz.yellow, width: 2.5),
        ),
      ),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Container(
            margin: const EdgeInsets.only(right: 10),
            width: 26,
            height: 26,
            alignment: Alignment.center,
            decoration: const BoxDecoration(
              color: Gz.ink,
              shape: BoxShape.circle,
            ),
            child: Text(
              '${b.sectionNo ?? ''}',
              style: const TextStyle(
                color: Gz.yellow,
                fontSize: 13,
                fontWeight: FontWeight.w900,
              ),
            ),
          ),
          Expanded(
            child: Padding(
              padding: const EdgeInsets.only(top: 3),
              child: Text(
                b.text,
                style: const TextStyle(
                  fontSize: 15.5,
                  fontWeight: FontWeight.w900,
                  height: 1.25,
                  letterSpacing: -0.2,
                  color: Gz.ink,
                ),
              ),
            ),
          ),
        ],
      ),
    );
  }
}

