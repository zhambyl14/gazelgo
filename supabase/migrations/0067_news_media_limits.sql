-- «Жаңалықтар» бакетінің ФАЙЛ ЛИМИТІ.
--
-- 0066-да бакет `file_size_limit` берілмей құрылды — сонда проекттің
-- ЖАЛПЫ лимиті қолданылады. Қосымша видеоны 40 МБ-қа дейін жібереді
-- (`news_admin_screen.dart`), сол себепті бакеттің өз лимитін АНЫҚ
-- жазып қоямыз: жалпы лимит кейін төмендетілсе де, модератордың видеосы
-- түсініксіз «413» қатесімен қайтарылмайды.
--
-- MIME тізімін ӘДЕЙІ ШЕКТЕМЕЙМІЗ: телефондар аудио/видеоны әртүрлі
-- Content-Type-пен жібереді (m4a → audio/mp4, кейде audio/x-m4a), ал
-- қатаң тізім оларды себепсіз бөгеп тастар еді. Кім жүктей алатынын
-- 0066-дағы `news_write_mod` саясаты (тек модератор) шешеді.
--
-- ЕСКЕРТУ: идемпотентті, SQL Editor-да ҚОЛМЕН орындалады. 0066-дан КЕЙІН.
-- ============================================================

update storage.buckets
   set public = true,
       file_size_limit = 52428800   -- 50 МБ
 where id = 'news';

