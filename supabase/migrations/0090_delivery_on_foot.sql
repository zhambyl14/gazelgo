--
-- ӨТЕ МАҢЫЗДЫ: бұл миграцияны жаңа қосымша нұсқасы шықпай тұрып қолданыңыз —
-- қосымша жаяу курьер өтінімінде осы бағанға жазады.
-- Идемпотентті. Supabase SQL Editor-да ҚОЛМЕН қолданылады (0089-дан кейін).
-- ============================================================

alter table public.executor_profiles
  add column if not exists delivery_on_foot boolean not null default false;

comment on column public.executor_profiles.delivery_on_foot is
  'Жаяу курьер («Доставка»): права/техпаспорт/көлік фотосы керек емес (0090)';
