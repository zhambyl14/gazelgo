-- ЖАЯУ КУРЬЕР: «Доставка» түріндегі орындаушы авто не жаяу болады.
-- Жаяу курьерге права, техпаспорт, көлік фотолары (4 жақ) КЕРЕК ЕМЕС —
-- тек профиль селфиі және жеке куәлік + куәлікпен селфи.
--
--   * executor_profiles.delivery_on_foot — жаяу курьер белгісі.
--     Заказдарды көру/қабылдау логикасы өзгермейді (vehicle_type әлі
--     'delivery'), сондықтан жаяу курьер де доставка заказдарын көреді.
--   * Қосымша: орындаушы өтінімінде «Авто / Жаяу» таңдайды; модератор
