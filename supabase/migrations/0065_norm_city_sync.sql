-- `norm_city` ҚАЙТА DART-ПЕН ҮЙЛЕСТІРІЛЕДІ.
--
-- 0013-те бұл функция «Dart-тағы Geo.normalizeCity-мен үйлеседі» деп
-- жазылған. Адрес таңдау түзетілгенде Dart жағындағы жұрнақ тізімі
-- кеңейтілді (Nominatim нақты қайтаратын түрлер бойынша), сол себепті
-- екеуі айырылып қалды. Осында тізім қайта теңестіріледі.
--
-- НЕ ҚОСЫЛАДЫ (бәрі Nominatim жауабынан алынған нақты түрлер):
--   · «әкімдігі» — «Ерейментау қаласы әкімдігі», «Риддер қалалық әкімдігі»
--     (бұрын «әкімшілігі» ғана бар еді; бұл — БАСҚА сөз, сол себепті
--     Ерейментау ешқашан тазаланбайтын);
--   · «қ.ә.», «а.ә.», «а.о.» — қысқартылған түрі («Текелі Қ.Ә.»);
--   · «қалалық», «аудандық», «ауылдық», «кенттік», «селолық», «округ»,
--     «округі» — «Қаскелең қалалық әкімдігі» екі қадамда тазаруы үшін;
--   · «кенті», «селосы», «сельский округ», «поселковый округ»,
--     «акимат», «акимат города», «посёлок», «поселок».
--
-- ЖӘНЕ ЖАҢА ЕРЕЖЕ: жұрнақ ЖЕКЕ СӨЗ болуы шарт (алдында бос орын не
-- үтір тұруы керек). Бұрын мұндай тексеріс жоқ еді де, `like '%город'`
-- «Белгород» → «Бел» деп атауды бүлдіретін. Dart жағында да дәл осылай.
--
-- НЕГЕ КЕРЕК: `exec_can_see` осы функция арқылы орындаушының қаласын
-- заказдың қаласымен салыстырады. Жаңа деректе екі жағы да таза атау
-- (kzCities тізімінен), бірақ ЕСКІ жазбаларда әкімшілік түрі сақталған:
-- ескі қосымша қаланы reverse-геокодтан шикі күйінде жазатын. Тізім
-- теңескенде сол ескі жазбалар да дұрыс салыстырылады.
--
-- ҚАУІПСІЗДІГІ: тек САЛЫСТЫРУҒА арналған таза функция, ешбір деректі
-- өзгертпейді. Схема өзгермейді, кері үйлесімді.
--
-- ЕСКЕРТУ: идемпотентті, SQL Editor-да ҚОЛМЕН қолданылады (Supabase MCP
-- бұл сессияда авторизацияланбаған). 0064-тен КЕЙІН орындаңыз.
-- ============================================================

create or replace function public.norm_city(p text)
returns text
language plpgsql immutable
set search_path = public, pg_temp
as $$
declare
  s text;
  suf text;
  cut int;
  -- Dart: Geo._cityAdminSuffixes (lib/core/geo.dart) — РЕТІ де сол.
  sufs text[] := array[
    'қалалық әкімшілігі','қаласының әкімшілігі','әкімшілігі','әкімдігі',
    'қ.ә.','а.ә.','а.о.',
    'қаласы','ауданы','ауданының','қаласының','облысы',
    'қалалық','аудандық','ауылдық','кенттік','селолық',
    'округі','округ','ауылы','кенті','селосы',
    'городская администрация','администрация города',
    'сельский округ','поселковый округ','акимат города','акимат',
    'города','город','село','посёлок','поселок','с.'];
  changed boolean := true;
begin
  if p is null then return null; end if;
  s := lower(btrim(p));
  if position(',' in s) > 0 then
    s := btrim(split_part(s, ',', 1));   -- «Тараз, Тараз ГА» → «тараз»
  end if;
  while changed loop
    changed := false;
    foreach suf in array sufs loop
      cut := length(s) - length(suf);
      -- Жұрнақ ЖЕКЕ СӨЗ болуы шарт: алдында бос орын не үтір тұрсын.
      -- Әйтпесе «белгород» → «бел» болып атау бүлінеді.
      if cut > 0 and right(s, length(suf)) = suf
         and substr(s, cut, 1) in (' ', ',', '-') then
        s := btrim(left(s, cut));
        changed := true;
        exit;                            -- тізімді басынан қайта жүреміз
      end if;
    end loop;
  end loop;
  return nullif(btrim(s, ' ,-'), '');
end;
$$;

revoke execute on function public.norm_city(text) from public, anon;

